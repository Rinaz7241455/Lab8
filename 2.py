# Контрольный пример (Фотография 2)
# Полиморфный расчёт баланса для трёх типов счетов

accounts = [
    ("Накопительный счёт", "40817-01", "Иванов А.А.", 120000.0, 120000.0 * 0.12 / 12),
    ("Кредитный счёт", "45502-02", "Петров В.С.", 50000.0, -450.0),
    ("Зарплатный счёт", "40817-03", "Сидорова М.И.", 35000.0, 500.0),
]

for acc_type, acc_id, owner, balance, diff in accounts:
    final_bal = balance + diff
    print(f"[{acc_type}] №{acc_id} ({owner})")
    print(f"Начальный баланс: {balance:.2f} руб. | Изменение: {diff:+.2f} руб. | Итого: {final_bal:.2f} руб.\n")
